-- =====================================================================
-- 羽球報名：讓網頁可以刪除報名名單上的人員
--
-- 本檔請在 Supabase 的 SQL Editor 整份貼上，按 Run 執行一次。
-- 重複執行也不會出錯。
--
-- 執行後：
-- - 任何人都能在羽球報名頁刪除名單上的人員（沒有登入、沒有核對）。
-- - 只能刪除「羽球報名」的資料，報修資料完全不受影響。
-- - 刪除後無法復原。
-- =====================================================================


-- ---------------------------------------------------------------------
-- 第 1 層：GRANT
-- - 訪客（anon）多一個權限：刪除資料列。
-- ---------------------------------------------------------------------
grant delete on table public.repair_requests to anon;


-- ---------------------------------------------------------------------
-- 第 2 層：RLS
-- - 只允許刪除地點為「羽球報名」的資料；
--   沒有符合這條規則的報修資料，刪除時會被略過（0 筆）。
-- ---------------------------------------------------------------------
drop policy if exists repair_requests_delete_badminton_anon on public.repair_requests;
create policy repair_requests_delete_badminton_anon
  on public.repair_requests
  for delete
  to anon
  using (location = '羽球報名');
